int32_t std_io_open(uint8_t *path, uint64_t len, int32_t mode, StdFile **out) {
    if (!out || !path || !len || len > INT64_MAX - 1 || mode < 0 || mode > 2) return STD_INVALID;
    if (memchr(path, 0, (size_t)len)) return STD_INVALID;
    char *name = NULL; StdFile *file = NULL;
    int32_t status = std_core_allocate(len + 1, 1, (void **)&name);
    if (status) return status;
    memcpy(name, path, (size_t)len);
    status = std_core_allocate(1, sizeof(*file), (void **)&file);
    if (status) { free(name); return status; }
    int flags = O_CLOEXEC | (mode == 0 ? O_RDONLY : O_WRONLY | O_CREAT | (mode == 1 ? O_TRUNC : O_APPEND));
    do { file->fd = open(name, flags, 0666); } while (file->fd < 0 && errno == EINTR);
    free(name);
    if (file->fd < 0) { free(file); return STD_IO; }
    *out = file; return STD_OK;
}
int32_t std_io_close(StdFile *file) {
    if (!file) return STD_OK;
    int result = close(file->fd);
    free(file);
    return result ? STD_IO : STD_OK;
}
int32_t std_io_read(StdFile *file, uint8_t *data, uint64_t capacity, uint64_t *count) {
    if (!file || !count || (capacity && !data)) return STD_INVALID;
    if (capacity > INT64_MAX) return STD_RANGE;
    if (!capacity) { *count = 0; return STD_OK; }
    ssize_t n;
    do { n = read(file->fd, data, (size_t)capacity); } while (n < 0 && errno == EINTR);
    if (n < 0) return STD_IO;
    *count = (uint64_t)n;
    return n ? STD_OK : STD_EOF;
}
int32_t std_io_write(StdFile *file, uint8_t *data, uint64_t len, uint64_t *count) {
    if (!file || !count || (len && !data)) return STD_INVALID;
    if (len > INT64_MAX) return STD_RANGE;
    *count = 0;
    sigset_t blocked, previous, pending;
    sigemptyset(&blocked); sigaddset(&blocked, SIGPIPE);
    if (sigprocmask(SIG_BLOCK, &blocked, &previous)) return STD_IO;
    if (sigpending(&pending)) { sigprocmask(SIG_SETMASK, &previous, NULL); return STD_IO; }
    int result = STD_OK;
    while (*count < len) {
        ssize_t n = write(file->fd, data + *count, (size_t)(len - *count));
        if (n < 0 && errno == EINTR) continue;
        if (n <= 0) {
            // Consume only a SIGPIPE generated by this call, preserving host state.
            if (n < 0 && errno == EPIPE && !sigismember(&pending, SIGPIPE)) {
                struct timespec zero = {0, 0};
                while (sigtimedwait(&blocked, NULL, &zero) < 0 && errno == EINTR) {}
            }
            result = STD_IO;
            break;
        }
        *count += (uint64_t)n;
    }
    if (sigprocmask(SIG_SETMASK, &previous, NULL)) result = STD_IO;
    return result;
}
int32_t std_io_stdout(uint8_t *data, uint64_t len) { StdFile f = {1}; uint64_t n; return std_io_write(&f,data,len,&n); }
int32_t std_io_stderr(uint8_t *data, uint64_t len) { StdFile f = {2}; uint64_t n; return std_io_write(&f,data,len,&n); }

int32_t std_time_monotonic(uint64_t *out) {
    if (!out) return STD_INVALID;
    struct timespec ts;
    if (clock_gettime(CLOCK_MONOTONIC, &ts)) return STD_IO;
    if (ts.tv_sec < 0 || (uint64_t)ts.tv_sec > (UINT64_MAX - (uint64_t)ts.tv_nsec) / 1000000000) return STD_RANGE;
    *out = (uint64_t)ts.tv_sec * 1000000000 + (uint64_t)ts.tv_nsec;
    return STD_OK;
}
int32_t std_time_unix(int64_t *out) {
    if (!out) return STD_INVALID;
    struct timespec ts;
    if (clock_gettime(CLOCK_REALTIME, &ts)) return STD_IO;
    __int128 n = (__int128)ts.tv_sec * 1000000000 + ts.tv_nsec;
    if (n < INT64_MIN || n > INT64_MAX) return STD_RANGE;
    *out = (int64_t)n; return STD_OK;
}
int32_t std_time_sleep(uint64_t n) {
    struct timespec ts = {(time_t)(n / 1000000000), (long)(n % 1000000000)};
    while (nanosleep(&ts, &ts)) if (errno != EINTR) return STD_IO;
    return STD_OK;
}
