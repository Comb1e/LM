int32_t std_core_allocate(uint64_t count, uint64_t size, void **out) {
    if (!out || !size) return STD_INVALID;
    if (count > INT64_MAX / size) return STD_RANGE;
    size_t bytes = (size_t)(count * size);
    void *p = calloc(bytes ? bytes : 1, 1);
    if (!p) return STD_NOMEM;
    memcpy(out, &p, sizeof(p));
    return STD_OK;
}
void std_core_release(void *p) { free(p); }
int32_t std_core_grow(void **data, uint64_t *capacity, uint64_t need, uint64_t width) {
    if (!data || !capacity || !width) return STD_INVALID;
    if (need > INT64_MAX / width) return STD_RANGE;
    if (need <= *capacity) return STD_OK;
    uint64_t n = *capacity ? *capacity : STD_INITIAL_CAPACITY;
    while (n < need) {
        if (n > (uint64_t)INT64_MAX / width / 2) { n = need; break; }
        n *= 2;
    }
    if (n > (uint64_t)INT64_MAX / width) n = need;
    void *base;
    memcpy(&base, data, sizeof(base));
    void *p = realloc(base, (size_t)(n * width));
    if (!p) return STD_NOMEM;
    memcpy(data, &p, sizeof(p)); *capacity = n;
    return STD_OK;
}
